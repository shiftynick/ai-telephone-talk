// Refreshes the numbers on the jev-axi slide's GitHub card (stars, forks, issues, release, commits, languages).
//   node tools/refresh-gh.mjs        (needs the `gh` CLI, logged in)
// Writes js/jev-axi-repo.js; the slide never fetches anything itself, so it works without venue Wi-Fi.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'shiftynick/jev-axi';
const gh = (...a) => execFileSync('gh', ['api', ...a], { encoding: 'utf8' });
const r = JSON.parse(gh(`repos/${REPO}`));
const langs = JSON.parse(gh(`repos/${REPO}/languages`));
const release = JSON.parse(gh(`repos/${REPO}/releases/latest`));
// the repo's open_issues_count includes pull requests; GitHub's tabs count them apart
const count = (q) => JSON.parse(gh(`search/issues?q=repo:${REPO}+${q}+is:open`)).total_count;
// the commit count is the page number of the last page at one commit per page
const link = gh('-i', `repos/${REPO}/commits?per_page=1`).match(/page=(\d+)>; rel="last"/);
const total = Object.values(langs).reduce((a, b) => a + b, 0);
const data = {
  owner: r.owner.login, name: r.name, visibility: r.visibility, description: r.description, topics: r.topics,
  stars: r.stargazers_count, forks: r.forks_count, issues: count('is:issue'), pulls: count('is:pr'), license: r.license?.spdx_id ?? null,
  release: release.tag_name, commits: link ? Number(link[1]) : null,
  languages: Object.entries(langs).map(([name, bytes]) => [name, Math.round((bytes / total) * 1000) / 10]),
  asOf: new Date().toISOString().slice(0, 10),
};
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'js', 'jev-axi-repo.js');
writeFileSync(out, `/* generated by tools/refresh-gh.mjs — the jev-axi slide's GitHub card */\nwindow.JEV_AXI_REPO = ${JSON.stringify(data, null, 2)};\n`);
console.log(`${REPO}: ★${data.stars} ⑂${data.forks} issues ${data.issues} ${data.release} ${data.commits} commits → ${path.relative(process.cwd(), out)}`);
